const PM_BY_ID = new Map<string, PmMeta>(
  PM_CATALOG.map((item) => [item.pmId.toUpperCase(), item])
);

export function resolvePmMeta(rawPmId: string, rawGroupId?: string | null): PmMeta {
  const key = String(rawPmId || "").trim().toUpperCase();
  const known = PM_BY_ID.get(key);
  if (known) return known;

  const grp = String(rawGroupId || "").trim().toLowerCase();
  let factory: PmMeta["factory"] = "Lainnya";
  if (grp === "ew21") factory = "Factory 1";
  else if (grp === "ew22" || grp === "ew23") factory = "Factory 2";

  return {
    pmId: key || "UNKNOWN",
    name: key || "Unknown Power Meter",
    factory,
    groupId: grp || "-",
    area: "Lainnya"
  };
}

export function isIncomingCubiclePm(pmId: string): boolean {
  const up = pmId.toUpperCase();
  return up === "PM410" || up === "PM411" || up === "PM412";
}
